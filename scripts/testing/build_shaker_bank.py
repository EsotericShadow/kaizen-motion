"""Build a deterministic PCM grain bank from attributed CC0 recorded shakers.
Run offline; never from the app/audio thread. Requires ffmpeg, NumPy and SciPy.
These are edited excerpts, not claims of independently recorded velocity layers.
"""
from pathlib import Path
import subprocess, json, hashlib
import numpy as np
from scipy.signal import find_peaks
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'Assets/Audio/Shaker'
manifest = json.loads((SRC/'sources.json').read_text())
clips=[]
for entry in manifest:
    raw=subprocess.check_output(['ffmpeg','-v','error','-i',str(SRC/'Sources'/entry['file']),'-f','f32le','-ac','1','-ar','48000','pipe:1'])
    audio=np.frombuffer(raw,dtype='<f4').copy()
    energy=np.sqrt(np.convolve(audio.astype(float)**2,np.ones(240)/240,mode='same'))
    peaks,_=find_peaks(energy,distance=2400,prominence=max(0.005,float(np.max(energy))*.06))
    candidates=sorted(peaks,key=lambda i:float(energy[i]),reverse=True)[:40]
    candidates.sort()
    for peak in candidates:
        start=max(0,int(peak)-120)
        data=audio[start:start+2048].copy()
        if len(data)<2048: data=np.pad(data,(0,2048-len(data)))
        data-=data.mean()
        rms=np.sqrt(np.mean(data**2))
        if rms<.003: continue
        data*=min(.16/rms,.8/max(.00001,float(np.max(np.abs(data)))))
        data[:24]*=np.linspace(0,1,24)
        data[-192:]*=np.linspace(1,0,192)
        clips.append((entry['file'],start,np.round(data*32767).astype(np.int16)))
# Interleave recordings for varied repeated contacts; 64 different recorded slices.
by_source=[[c for c in clips if c[0]==e['file']] for e in manifest]
selected=[]
for index in range(max(map(len,by_source))):
    for group in by_source:
        if index<len(group): selected.append(group[index])
selected=selected[:64]
assert len(selected)>=32, len(selected)
header=ROOT/'Packages/MotionCore/Sources/MotionToneDSP/ShakerSampleBank.h'
with header.open('w') as f:
    f.write('// Generated by scripts/testing/build_shaker_bank.py from CC0 sources.\n// Provenance: Assets/Audio/Shaker/sources.json and bank.json.\n')
    f.write(f'#define KM_SHAKER_SAMPLE_COUNT {len(selected)}\n#define KM_SHAKER_SAMPLE_FRAMES 2048\nstatic const int16_t kmShakerPCM[KM_SHAKER_SAMPLE_COUNT][KM_SHAKER_SAMPLE_FRAMES] = {{\n')
    for _,_,data in selected: f.write('{'+','.join(map(str,data))+'},\n')
    f.write('};\n')
(SRC/'bank.json').write_text(json.dumps({'sample_rate':48000,'frames_per_excerpt':2048,'excerpts':[{'source':c[0],'start_frame':c[1]} for c in selected],'header_sha256':hashlib.sha256(header.read_bytes()).hexdigest()},indent=2)+'\n')
print(f'Built {len(selected)} distinct recorded excerpts, {len(selected)*2048*2} PCM bytes')
